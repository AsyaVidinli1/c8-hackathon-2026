function t(key) {
  var d = i18n[state.lang] || i18n.tr;
  return key in d ? d[key] : key;
}

function tf(key, vars) {
  var s = t(key);
  for (var k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

function loc(field) {
  if (field && typeof field === "object" && !Array.isArray(field)) {
    if (state.lang in field) return field[state.lang];
    if ("tr" in field) return field.tr;
    if ("en" in field) return field.en;
    return "";
  }
  return field == null ? "" : field;
}

function applyStaticTranslations() {
  document.documentElement.lang = state.lang;
  document.title = t("app_title");
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll(".lang-btn").forEach(function (b) {
    b.classList.toggle("active", b.dataset.lang === state.lang);
  });
}

function setLang(lang) {
  state.lang = lang;
  applyStaticTranslations();
  persistState();
  if (state.currentUserId) window.renderShell();
}
